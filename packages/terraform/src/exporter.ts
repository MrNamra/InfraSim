const FIXED_ZIP_MTIME = new Date(Date.UTC(2026, 0, 1, 0, 0, 0));

function detectDesignProviders(
  design: Design,
  options?: TerraformExportOptions,
): CloudProviderId[] {
  if (options?.providers && options.providers.length > 0) {
    const picked = new Set<CloudProviderId>();
    for (const p of options.providers) {
      if (p === 'aws' || p === 'gcp' || p === 'azure' || p === 'oci') {
        picked.add(p);
      }
    }
    return [...picked].sort();
  }

  const found = new Set<CloudProviderId>();
  const primary = normalizeCloudProvider(design.settings.primaryProvider);
  for (const node of design.nodes) {
    const p = inferCloudProviderForServiceId(node.serviceId, primary);
    if (p === 'aws' || p === 'gcp' || p === 'azure' || p === 'oci') {
      found.add(p);
    }
  }
  for (const group of design.groups) {
    if (
      group.provider === 'aws' ||
      group.provider === 'gcp' ||
      group.provider === 'azure' ||
      group.provider === 'oci'
    ) {
      found.add(group.provider);
    }
  }
  for (const net of design.network?.networks ?? []) {
    if (
      net.provider === 'aws' ||
      net.provider === 'gcp' ||
      net.provider === 'azure' ||
      net.provider === 'oci'
    ) {
      found.add(net.provider);
    }
  }
  if (found.size === 0) {
    found.add(primary);
  }
  return [...found].sort();
}

function buildTerraformSettingsBlock(providersIncluded: readonly CloudProviderId[]): HclBlock {
  const providerKeyMap: Record<CloudProviderId, keyof typeof TERRAFORM_PROVIDERS_CONFIG.providers> =
    {
      aws: 'aws',
      gcp: 'google',
      azure: 'azurerm',
      oci: 'oci',
    };

  const reqEntries = providersIncluded.map((p): [string, ReturnType<typeof hclMap>] => {
    const key = providerKeyMap[p];
    const spec = TERRAFORM_PROVIDERS_CONFIG.providers[key];
    return [
      key,
      hclMap([
        ['source', hclLit(spec.source)],
        ['version', hclLit(spec.version)],
      ]),
    ];
  });

  return hclBlock('terraform', {
    comments: ['Pin Terraform CLI and provider version constraints cleanly.'],
    attributes: [hclAttr('required_version', hclLit(TERRAFORM_PROVIDERS_CONFIG.terraformVersion))],
    blocks: [
      hclBlock('required_providers', {
        attributes: reqEntries.map(([k, val]) => hclAttr(k, val)),
      }),
    ],
  });
}

function buildVariablesStatements(ctx: TerraformExportContext): HclStatement[] {
  const specs: TerraformVariableSpec[] = [...ctx.variables.values()].sort((a, b) => {
    if (a.name === 'name_prefix') return -1;
    if (b.name === 'name_prefix') return 1;
    const aReg = a.name.endsWith('_region');
    const bReg = b.name.endsWith('_region');
    if (aReg !== bReg) return aReg ? -1 : 1;
    return a.name.localeCompare(b.name);
  });

  return specs.map((spec) => {
    const attrs: HclAttribute[] = [
      hclAttr('type', hclRef(spec.type)),
      hclAttr('description', hclLit(spec.description)),
    ];
    if (spec.sensitive) {
      attrs.push(hclAttr('sensitive', hclLit(true)));
    } else if (spec.defaultValue !== undefined) {
      attrs.push(hclAttr('default', hclLit(spec.defaultValue)));
    }
    return hclBlockStmt(
      hclBlock('variable', {
        labels: [spec.name],
        ...(spec.comment && ctx.includeComments ? { comments: [spec.comment] } : {}),
        attributes: attrs,
      }),
    );
  });
}

function buildReadme(ctx: TerraformExportContext, resourceCount: number): string {
  const lines: string[] = [
    `# ${ctx.design.name} — Terraform Export`,
    '',
    '> **Generated by InfraSim for learning. Review before applying.**',
    '> Applying this configuration creates real cloud infrastructure that costs real money.',
    '',
    '## Overview',
    '',
    `- **Providers:** ${ctx.providersIncluded.map((p) => p.toUpperCase()).join(', ')}`,
    `- **Resource blocks generated:** ${resourceCount}`,
    `- **Name prefix:** \`${ctx.namePrefix}\``,
    '',
    '## Review checklist before running `terraform plan`',
    '',
    '1. Review `variables.tf` and supply any sensitive variables (such as database passwords or API keys) via environment variables (`export TF_VAR_<name>=...`) or a secure secrets manager — never commit `.tfvars` secrets to Git.',
    '2. Check any `# TODO:` comments for customer-specific parameters (domain names, container images, SSH key pairs, or secondary AZ subnets).',
    '3. Verify security group rules and IAM roles match your least-privilege organizational policy.',
    '4. Run `terraform init && terraform plan -out=tfplan` to inspect proposed changes before `apply`.',
  ];

  if (ctx.unsupportedNodes.length > 0) {
    lines.push('', '## Unsupported canvas items (manual setup needed)', '');
    for (const item of ctx.unsupportedNodes) {
      lines.push(`- **${item.label}** (\`${item.serviceId}\`): ${item.reason}`);
    }
  }

  lines.push('');
  return lines.join('\n');
}

function countResourceBlocks(statements: readonly HclStatement[]): number {
  let count = 0;
  for (const s of statements) {
    if (s.kind === 'block' && s.block.type === 'resource') {
      count++;
    }
  }
  return count;
}

/**
 * Deterministically converts an InfraSim Design into idiomatic Terraform HCL files and README.md.
 */
export function exportDesignToTerraform(
  design: Design,
  options?: TerraformExportOptions,
): TerraformExportResult {
  const providersIncluded = detectDesignProviders(design, options);
  const ctx = createExportContext(design, providersIncluded, options);

  ctx.addVariable({
    name: 'name_prefix',
    type: 'string',
    defaultValue: ctx.namePrefix,
    description: 'Prefix applied to all generated resource names and Name tags.',
  });

  const header = GENERATED_FILE_HEADER_COMMENTS;
  const providerMappers: Record<CloudProviderId, (c: TerraformExportContext) => void> = {
    aws: mapAwsToTerraform,
    gcp: mapGcpToTerraform,
    azure: mapAzureToTerraform,
    oci: mapOciToTerraform,
  };

  const perProviderFiles: TerraformGeneratedFile[] = [];
  let resourceCount = 0;

  if (providersIncluded.length <= 1) {
    for (const prov of providersIncluded) {
      providerMappers[prov](ctx);
    }

    // Handle custom / unmapped non-generic nodes across the canvas deterministically
    for (const node of [...design.nodes].sort((a, b) => a.id.localeCompare(b.id))) {
      const p = inferCloudProviderForServiceId(node.serviceId);
      if (p === 'generic') continue;
      if (p === 'custom') {
        const msg = `InfraSim: no Terraform mapping for ${node.serviceId} (${node.label})`;
        ctx.buckets.compute.push(hclCommentStmt(msg));
        ctx.addUnsupported(node, 'Custom user service cannot be mapped automatically to Terraform');
      }
    }

    perProviderFiles.push(
      {
        filename: 'network.tf',
        language: 'hcl',
        content: printHclFile(
          hclFile(
            'network.tf',
            ctx.buckets.network.length > 0
              ? ctx.buckets.network
              : [hclCommentStmt('No virtual network resources defined in this design.')],
            header,
          ),
        ),
      },
      {
        filename: 'compute.tf',
        language: 'hcl',
        content: printHclFile(
          hclFile(
            'compute.tf',
            ctx.buckets.compute.length > 0
              ? ctx.buckets.compute
              : [hclCommentStmt('No compute resources defined in this design.')],
            header,
          ),
        ),
      },
      {
        filename: 'data.tf',
        language: 'hcl',
        content: printHclFile(
          hclFile(
            'data.tf',
            ctx.buckets.data.length > 0
              ? ctx.buckets.data
              : [
                  hclCommentStmt(
                    'No database, cache, queue, or storage resources defined in this design.',
                  ),
                ],
            header,
          ),
        ),
      },
    );

    if (ctx.buckets.ai.length > 0) {
      perProviderFiles.push({
        filename: 'ai.tf',
        language: 'hcl',
        content: printHclFile(hclFile('ai.tf', ctx.buckets.ai, header)),
      });
    }

    resourceCount =
      countResourceBlocks(ctx.buckets.network) +
      countResourceBlocks(ctx.buckets.compute) +
      countResourceBlocks(ctx.buckets.data) +
      countResourceBlocks(ctx.buckets.ai);
  } else {
    for (const prov of providersIncluded) {
      const scopedCtx: TerraformExportContext = {
        ...ctx,
        buckets: {
          providers: ctx.buckets.providers,
          network: [],
          compute: [],
          data: [],
          ai: [],
          outputs: ctx.buckets.outputs,
        },
      };
      providerMappers[prov](scopedCtx);

      const pPrefix = `${prov}_`;
      const provCount =
        countResourceBlocks(scopedCtx.buckets.network) +
        countResourceBlocks(scopedCtx.buckets.compute) +
        countResourceBlocks(scopedCtx.buckets.data) +
        countResourceBlocks(scopedCtx.buckets.ai);
      resourceCount += provCount;

      if (scopedCtx.buckets.network.length > 0) {
        perProviderFiles.push({
          filename: `${pPrefix}network.tf`,
          language: 'hcl',
          content: printHclFile(hclFile(`${pPrefix}network.tf`, scopedCtx.buckets.network, header)),
        });
      }
      if (scopedCtx.buckets.compute.length > 0) {
        perProviderFiles.push({
          filename: `${pPrefix}compute.tf`,
          language: 'hcl',
          content: printHclFile(hclFile(`${pPrefix}compute.tf`, scopedCtx.buckets.compute, header)),
        });
      }
      if (scopedCtx.buckets.data.length > 0) {
        perProviderFiles.push({
          filename: `${pPrefix}data.tf`,
          language: 'hcl',
          content: printHclFile(hclFile(`${pPrefix}data.tf`, scopedCtx.buckets.data, header)),
        });
      }
      if (scopedCtx.buckets.ai.length > 0) {
        perProviderFiles.push({
          filename: `${pPrefix}ai.tf`,
          language: 'hcl',
          content: printHclFile(hclFile(`${pPrefix}ai.tf`, scopedCtx.buckets.ai, header)),
        });
      }
    }

    // Handle custom nodes across multi-cloud designs
    const customComments: HclStatement[] = [];
    for (const node of [...design.nodes].sort((a, b) => a.id.localeCompare(b.id))) {
      if (inferCloudProviderForServiceId(node.serviceId) === 'custom') {
        customComments.push(
          hclCommentStmt(`InfraSim: no Terraform mapping for ${node.serviceId} (${node.label})`),
        );
        ctx.addUnsupported(node, 'Custom user service cannot be mapped automatically to Terraform');
      }
    }
    if (customComments.length > 0) {
      perProviderFiles.push({
        filename: 'custom_stubs.tf',
        language: 'hcl',
        content: printHclFile(hclFile('custom_stubs.tf', customComments, header)),
      });
    }
  }

  const providersStatements: HclStatement[] = [
    hclBlockStmt(buildTerraformSettingsBlock(providersIncluded)),
    ...ctx.buckets.providers,
  ];

  const variablesStatements = buildVariablesStatements(ctx);

  const outputsStatements: HclStatement[] =
    ctx.buckets.outputs.length > 0
      ? ctx.buckets.outputs
          .slice()
          .sort((a, b) => a.name.localeCompare(b.name))
          .map((out) =>
            hclBlockStmt(
              hclBlock('output', {
                labels: [out.name],
                attributes: [
                  hclAttr('description', hclLit(out.description)),
                  hclAttr('value', hclRef(out.valueRef)),
                  ...(out.sensitive ? [hclAttr('sensitive', hclLit(true))] : []),
                ],
              }),
            ),
          )
      : [hclCommentStmt('No stack outputs declared for this design.')];

  const files: TerraformGeneratedFile[] = [
    {
      filename: 'providers.tf',
      language: 'hcl',
      content: printHclFile(hclFile('providers.tf', providersStatements, header)),
    },
    {
      filename: 'variables.tf',
      language: 'hcl',
      content: printHclFile(hclFile('variables.tf', variablesStatements, header)),
    },
    ...perProviderFiles,
    {
      filename: 'outputs.tf',
      language: 'hcl',
      content: printHclFile(hclFile('outputs.tf', outputsStatements, header)),
    },
    {
      filename: 'README.md',
      language: 'markdown',
      content: buildReadme(ctx, resourceCount),
    },
  ];

  if (ctx.unsupportedNodes.length > 0) {
    ctx.warnings.push(
      `${ctx.unsupportedNodes.length} service(s) have no direct Terraform mapping and were emitted as commented stubs.`,
    );
  }

  return {
    files,
    providersIncluded,
    resourceCount,
    unsupportedNodes: ctx.unsupportedNodes,
    warnings: ctx.warnings,
    resourceAddresses: ctx.resourceAddresses,
  };
}

/**
 * Packages exported Terraform files into a deterministic client-side ZIP archive (`terraform/`).
 */
export function exportTerraformZip(
  input: Design | TerraformExportResult,
  options?: TerraformExportOptions,
): Uint8Array {
  const result = 'files' in input ? input : exportDesignToTerraform(input, options);
  const entries: Record<string, [Uint8Array, { level: 6; mtime: Date }]> = {};
  for (const file of result.files) {
    entries[`terraform/${file.filename}`] = [
      strToU8(file.content),
      { level: 6, mtime: FIXED_ZIP_MTIME },
    ];
  }
  return zipSync(entries);
}
