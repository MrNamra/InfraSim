import { CATALOG_SERVICES } from '@infrasim/catalog';
import {
  createEmptyNetworkConfig,
  type Design,
  type FirewallObject,
  type GroupInstance,
  type NetworkConfig,
  type NodeInstance,
  type Provider,
  type ServiceDefinition,
} from '@infrasim/shared-types';
import { TerraformNameAllocator, snakeCaseSlug } from '../naming.js';
import type { HclStatement, TerraformExportOptions, UnsupportedNodeNotice } from '../types.js';

export type CloudProviderId = 'aws' | 'gcp' | 'azure' | 'oci';

export interface TerraformVariableSpec {
  name: string;
  type: 'string' | 'number' | 'bool';
  description: string;
  defaultValue?: string | number | boolean;
  sensitive?: boolean;
  comment?: string;
}

export interface TerraformOutputSpec {
  name: string;
  description: string;
  valueRef: string;
  sensitive?: boolean;
}

export interface TerraformExportFileBuckets {
  providers: HclStatement[];
  network: HclStatement[];
  compute: HclStatement[];
  data: HclStatement[];
  ai: HclStatement[];
  outputs: TerraformOutputSpec[];
}

export interface TerraformExportContext {
  design: Design;
  namePrefix: string;
  includeComments: boolean;
  regions: Record<CloudProviderId, string>;
  providersIncluded: CloudProviderId[];
  allocator: TerraformNameAllocator;
  network: Required<NetworkConfig>;
  groupsById: ReadonlyMap<string, GroupInstance>;
  nodesById: ReadonlyMap<string, NodeInstance>;
  servicesById: ReadonlyMap<string, ServiceDefinition>;
  variables: Map<string, TerraformVariableSpec>;
  buckets: TerraformExportFileBuckets;
  unsupportedNodes: UnsupportedNodeNotice[];
  warnings: string[];
  resourceAddresses: Record<string, string[]>;
  addVariable: (spec: TerraformVariableSpec) => string;
  addOutput: (spec: TerraformOutputSpec) => void;
  recordAddress: (entityId: string, address: string) => void;
  addUnsupported: (node: NodeInstance, reason: string) => void;
  resolveNodeRegion: (node: NodeInstance, provider: CloudProviderId) => string;
  resolveNodeAncestry: (node: NodeInstance) => {
    subnetGroup?: GroupInstance;
    vpcGroup?: GroupInstance;
    regionGroup?: GroupInstance;
    azGroup?: GroupInstance;
  };
  getNodeFirewall: (node: NodeInstance) => FirewallObject | undefined;
}

const DEFAULT_REGIONS: Record<CloudProviderId, string> = {
  aws: 'us-east-1',
  gcp: 'us-central1',
  azure: 'eastus',
  oci: 'us-ashburn-1',
};

const BUILTIN_SERVICES = new Map<string, ServiceDefinition>(CATALOG_SERVICES.map((s) => [s.id, s]));

export const GENERATED_FILE_HEADER_COMMENTS: string[] = [
  'Generated by InfraSim for learning. Review before applying.',
  'Applying creates real cloud resources that cost real money.',
];

/** Determines the cloud provider for a canvas node or group if applicable. */
export function inferCloudProviderForServiceId(
  serviceId: string,
  fallback: CloudProviderId = 'aws',
): CloudProviderId | 'generic' | 'custom' {
  const prefix = serviceId.split('.')[0];
  if (prefix === 'aws' || prefix === 'gcp' || prefix === 'azure' || prefix === 'oci') {
    return prefix;
  }
  if (prefix === 'generic') return 'generic';
  if (prefix === 'custom') return 'custom';
  return fallback;
}

/** Normalizes a Design's primary provider into one of the four cloud providers. */
export function normalizeCloudProvider(provider?: Provider): CloudProviderId {
  if (provider === 'aws' || provider === 'gcp' || provider === 'azure' || provider === 'oci') {
    return provider;
  }
  return 'aws';
}

/** Resolves default regions per provider from options, design groups/nodes, and provider defaults. */
export function resolveProviderRegions(
  design: Design,
  options?: TerraformExportOptions,
): Record<CloudProviderId, string> {
  const out: Record<CloudProviderId, string> = { ...DEFAULT_REGIONS };

  for (const group of design.groups) {
    if (group.region?.trim()) {
      const prov = group.provider
        ? normalizeCloudProvider(group.provider)
        : normalizeCloudProvider(design.settings.primaryProvider);
      out[prov] = group.region.trim();
    }
  }
  for (const node of design.nodes) {
    if (node.region?.trim()) {
      const p = inferCloudProviderForServiceId(node.serviceId);
      if (p === 'aws' || p === 'gcp' || p === 'azure' || p === 'oci') {
        out[p] = node.region.trim();
      }
    }
  }
  if (options?.regions) {
    for (const key of ['aws', 'gcp', 'azure', 'oci'] as const) {
      const v = options.regions[key]?.trim();
      if (v) out[key] = v;
    }
  }
  return out;
}

/** Builds the shared Terraform export context used across provider mapping modules. */
export function createExportContext(
  design: Design,
  providersIncluded: CloudProviderId[],
  options?: TerraformExportOptions,
): TerraformExportContext {
  const allocator = new TerraformNameAllocator();
  const baseNet = createEmptyNetworkConfig();
  const network: Required<NetworkConfig> = {
    networks: [...(design.network?.networks ?? baseNet.networks)],
    subnets: [...(design.network?.subnets ?? baseNet.subnets)],
    routeTables: [...(design.network?.routeTables ?? baseNet.routeTables)],
    gateways: [...(design.network?.gateways ?? baseNet.gateways)],
    firewalls: [...(design.network?.firewalls ?? baseNet.firewalls)],
    peerings: [...(design.network?.peerings ?? baseNet.peerings)],
    dnsZones: [...(design.network?.dnsZones ?? baseNet.dnsZones)],
    endpoints: [...(design.network?.endpoints ?? baseNet.endpoints)],
    attachments: [...(design.network?.attachments ?? baseNet.attachments)],
  };

  const groupsById = new Map(design.groups.map((g) => [g.id, g]));
  const nodesById = new Map(design.nodes.map((n) => [n.id, n]));
  const servicesById = new Map<string, ServiceDefinition>(BUILTIN_SERVICES);
  for (const custom of design.customServices ?? []) {
    servicesById.set(custom.id, custom);
  }

  const regions = resolveProviderRegions(design, options);
  const namePrefix = snakeCaseSlug(options?.namePrefix ?? design.name, 'infrasim').replace(
    /_/g,
    '-',
  );

  const variables = new Map<string, TerraformVariableSpec>();
  const outputs: TerraformOutputSpec[] = [];
  const unsupportedNodes: UnsupportedNodeNotice[] = [];
  const warnings: string[] = [];
  const resourceAddresses: Record<string, string[]> = {};

  // Pre-allocate core entity scopes in canonical sorted order so array order never affects names
  allocator.preallocate([
    ...design.groups.map((g) => ({
      scope: `group:${g.kind}`,
      entityId: g.id,
      rawLabel: g.label,
      fallback: g.kind,
    })),
    ...design.nodes.map((n) => ({
      scope: 'node',
      entityId: n.id,
      rawLabel: n.label,
      fallback: 'service',
    })),
    ...network.networks.map((n) => ({
      scope: 'network',
      entityId: n.id,
      rawLabel: n.name || n.id,
      fallback: 'main',
    })),
    ...network.subnets.map((s) => ({
      scope: 'subnet',
      entityId: s.id,
      rawLabel: s.id.replace(/^sub-/, ''),
      fallback: 'subnet',
    })),
  ]);

  const ctx: TerraformExportContext = {
    design,
    namePrefix,
    includeComments: options?.includeComments !== false,
    regions,
    providersIncluded,
    allocator,
    network,
    groupsById,
    nodesById,
    servicesById,
    variables,
    buckets: {
      providers: [],
      network: [],
      compute: [],
      data: [],
      ai: [],
      outputs,
    },
    unsupportedNodes,
    warnings,
    resourceAddresses,
    addVariable(spec) {
      const existing = variables.get(spec.name);
      if (!existing) {
        variables.set(spec.name, spec);
      }
      return spec.name;
    },
    addOutput(spec) {
      if (!outputs.some((o) => o.name === spec.name)) {
        outputs.push(spec);
      }
    },
    recordAddress(entityId, address) {
      const list = resourceAddresses[entityId] ?? [];
      if (!list.includes(address)) {
        list.push(address);
        resourceAddresses[entityId] = list;
      }
    },
    addUnsupported(node, reason) {
      unsupportedNodes.push({
        nodeId: node.id,
        serviceId: node.serviceId,
        label: node.label,
        reason,
      });
    },
    resolveNodeAncestry(node) {
      let subnetGroup: GroupInstance | undefined;
      let vpcGroup: GroupInstance | undefined;
      let regionGroup: GroupInstance | undefined;
      let azGroup: GroupInstance | undefined;
      let cursor = node.parentGroupId ? groupsById.get(node.parentGroupId) : undefined;
      const visited = new Set<string>();
      while (cursor && !visited.has(cursor.id)) {
        visited.add(cursor.id);
        if (cursor.kind === 'subnet' && !subnetGroup) subnetGroup = cursor;
        else if (cursor.kind === 'vpc' && !vpcGroup) vpcGroup = cursor;
        else if (cursor.kind === 'region' && !regionGroup) regionGroup = cursor;
        else if ((cursor.kind === 'az' || cursor.kind === 'zone') && !azGroup) azGroup = cursor;
        cursor = cursor.parentGroupId ? groupsById.get(cursor.parentGroupId) : undefined;
      }
      return {
        ...(subnetGroup ? { subnetGroup } : {}),
        ...(vpcGroup ? { vpcGroup } : {}),
        ...(regionGroup ? { regionGroup } : {}),
        ...(azGroup ? { azGroup } : {}),
      };
    },
    resolveNodeRegion(node, provider) {
      if (node.region?.trim()) return node.region.trim();
      const anc = ctx.resolveNodeAncestry(node);
      if (anc.regionGroup?.region?.trim()) return anc.regionGroup.region.trim();
      if (anc.vpcGroup?.region?.trim()) return anc.vpcGroup.region.trim();
      return regions[provider];
    },
    getNodeFirewall(node) {
      const att = network.attachments.find((a) => a.nodeId === node.id);
      if (att) {
        for (const fwId of att.firewallIds) {
          const fw = network.firewalls.find((f) => f.id === fwId && f.kind === 'sg');
          if (fw) return fw;
        }
      }
      return network.firewalls.find(
        (f) => f.kind === 'sg' && f.attachedTo?.nodeIds?.includes(node.id),
      );
    },
  };

  return ctx;
}
