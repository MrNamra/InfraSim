import { describe, expect, it } from 'vitest';
import {
  hclAttr,
  hclBlock,
  hclBlockStmt,
  hclCommentStmt,
  hclFile,
  hclList,
  hclLit,
  hclMap,
  hclRef,
} from './ast.js';
import { printHclFile } from './printer.js';
import { validateHclSyntax } from './validator.js';

describe('HCL AST printer and validator', () => {
  it('renders deterministic terraform fmt aligned HCL and validates cleanly', () => {
    const ast = hclFile(
      'main.tf',
      [
        hclBlockStmt(
          hclBlock('resource', {
            labels: ['aws_vpc', 'main'],
            comments: ['Primary VPC'],
            attributes: [
              hclAttr('cidr_block', hclLit('10.0.0.0/16')),
              hclAttr('enable_dns_support', hclLit(true)),
              hclAttr(
                'tags',
                hclMap([
                  ['Name', hclLit('app-${env}')],
                  ['Escaped', hclLit('line1\nline2 "quoted"')],
                ]),
              ),
              hclAttr('cidrs', hclList([hclLit('10.0.0.0/16'), hclLit('10.1.0.0/16')])),
              hclAttr('owner', hclRef('var.name_prefix')),
            ],
          }),
        ),
        hclCommentStmt('Standalone comment'),
      ],
      ['Generated by InfraSim for learning.'],
    );

    const rendered = printHclFile(ast);
    expect(rendered).toContain('cidr_block         = "10.0.0.0/16"');
    expect(rendered).toContain('Name    = "app-$${env}"');
    expect(rendered).toContain('Escaped = "line1\\nline2 \\"quoted\\""');

    const validation = validateHclSyntax(rendered, 'main.tf');
    expect(validation.valid).toBe(true);
    expect(validation.errors).toEqual([]);
    expect(validation.blockCount).toBe(1);
  });

  it('detects syntax errors such as unclosed blocks and missing equals', () => {
    const bad = validateHclSyntax(
      'resource "aws_vpc" "main" {\n  cidr_block = "10.0.0.0/16"\n',
      'bad.tf',
    );
    expect(bad.valid).toBe(false);
    expect(bad.errors.length).toBeGreaterThan(0);

    const badAttr = validateHclSyntax(
      'resource "aws_vpc" "main" {\n  cidr_block "10.0.0.0/16"\n}',
      'bad2.tf',
    );
    expect(badAttr.valid).toBe(false);
  });
});
