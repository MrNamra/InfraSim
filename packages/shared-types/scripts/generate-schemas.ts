import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGenerator } from 'ts-json-schema-generator';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgDir = path.resolve(__dirname, '..');
const schemaJsonPath = path.join(pkgDir, 'schemas', 'design.schema.json');
const schemaTsPath = path.join(pkgDir, 'src', 'generated', 'designSchema.ts');

const config = {
  tsconfig: path.join(pkgDir, 'tsconfig.json'),
  type: 'Design',
  expose: 'all' as const,
  topRef: true,
  jsDoc: 'extended' as const,
};

const schema = createGenerator(config).createSchema('Design');
const jsonOutput = `${JSON.stringify(schema, null, 2)}\n`;
const tsOutput = `// Auto-generated by scripts/generate-schemas.ts. Do not edit manually.\nexport const designJsonSchema = ${JSON.stringify(schema, null, 2)} as const;\n`;

const isCheck = process.argv.includes('--check');

if (isCheck) {
  const existingJson = fs.existsSync(schemaJsonPath) ? fs.readFileSync(schemaJsonPath, 'utf8') : '';
  const existingTs = fs.existsSync(schemaTsPath) ? fs.readFileSync(schemaTsPath, 'utf8') : '';
  if (existingJson !== jsonOutput || existingTs !== tsOutput) {
    console.error(
      'Design JSON Schema is out of date. Run `pnpm schema:generate` and commit the updated schema.',
    );
    process.exit(1);
  }
  console.log('Design JSON Schema is up to date.');
} else {
  fs.mkdirSync(path.dirname(schemaJsonPath), { recursive: true });
  fs.mkdirSync(path.dirname(schemaTsPath), { recursive: true });
  fs.writeFileSync(schemaJsonPath, jsonOutput, 'utf8');
  fs.writeFileSync(schemaTsPath, tsOutput, 'utf8');
  console.log(`Wrote ${schemaJsonPath} and ${schemaTsPath}`);
}
