import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGenerator } from 'ts-json-schema-generator';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgDir = path.resolve(__dirname, '..');
const catalogSchemaPath = path.resolve(pkgDir, '..', 'catalog', 'schemas', 'catalog.schema.json');
const schemaJsonPath = path.join(pkgDir, 'schemas', 'design.schema.json');
const schemaTsPath = path.join(pkgDir, 'src', 'generated', 'designSchema.ts');

const baseConfig = {
  tsconfig: path.join(pkgDir, 'tsconfig.json'),
  expose: 'all' as const,
  topRef: true,
  jsDoc: 'extended' as const,
};

const schema = createGenerator({ ...baseConfig, type: 'Design' }).createSchema('Design');
const catalogSchema = createGenerator({
  ...baseConfig,
  type: 'CatalogServiceList',
}).createSchema('CatalogServiceList');

const jsonOutput = `${JSON.stringify(schema, null, 2)}\n`;
const catalogJsonOutput = `${JSON.stringify(catalogSchema, null, 2)}\n`;
const tsOutput = `// Auto-generated by scripts/generate-schemas.ts. Do not edit manually.\nexport const designJsonSchema = ${JSON.stringify(schema, null, 2)} as const;\n`;

const isCheck = process.argv.includes('--check');

if (isCheck) {
  const existingJson = fs.existsSync(schemaJsonPath) ? fs.readFileSync(schemaJsonPath, 'utf8') : '';
  const existingTs = fs.existsSync(schemaTsPath) ? fs.readFileSync(schemaTsPath, 'utf8') : '';
  const existingCatalog = fs.existsSync(catalogSchemaPath)
    ? fs.readFileSync(catalogSchemaPath, 'utf8')
    : '';
  if (
    existingJson !== jsonOutput ||
    existingTs !== tsOutput ||
    existingCatalog !== catalogJsonOutput
  ) {
    console.error(
      'Generated JSON Schemas are out of date. Run `pnpm schema:generate` and commit the updated files.',
    );
    process.exit(1);
  }
  console.log('Design & Catalog JSON Schemas are up to date.');
} else {
  fs.mkdirSync(path.dirname(schemaJsonPath), { recursive: true });
  fs.mkdirSync(path.dirname(schemaTsPath), { recursive: true });
  fs.mkdirSync(path.dirname(catalogSchemaPath), { recursive: true });
  fs.writeFileSync(schemaJsonPath, jsonOutput, 'utf8');
  fs.writeFileSync(schemaTsPath, tsOutput, 'utf8');
  fs.writeFileSync(catalogSchemaPath, catalogJsonOutput, 'utf8');
  console.log(`Wrote ${schemaJsonPath}, ${schemaTsPath}, and ${catalogSchemaPath}`);
}
