import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG_DIR = path.join(ROOT_DIR, 'packages', 'catalog', 'data');
const COST_DATA_DIR = path.join(ROOT_DIR, 'packages', 'cost-engine', 'data');
const GENERATED_TS_PATH = path.join(
  ROOT_DIR,
  'packages',
  'cost-engine',
  'src',
  'generated',
  'costData.ts',
);
const REPORT_PATH = path.join(ROOT_DIR, 'docs', 'price-coverage.md');

interface CatalogServiceRow {
  id: string;
  provider: 'aws' | 'gcp' | 'azure' | 'oci';
  name: string;
  pricing?: { model?: string };
}

interface SkuMappingEntry {
  serviceId: string;
  provider: 'aws' | 'gcp' | 'azure' | 'oci';
  unitRole: string;
  unit: string;
  filter: Record<string, unknown>;
}

interface UnavailableEntry {
  serviceId: string;
  provider: 'aws' | 'gcp' | 'azure' | 'oci';
  reason: string;
}

interface PriceSkuMapFile {
  version: number;
  updatedAt: string;
  mappings: SkuMappingEntry[];
  knownUnavailable?: UnavailableEntry[];
}

const PROVIDERS = ['aws', 'gcp', 'azure', 'oci'] as const;

function readJson<T>(filePath: string): T {
  return JSON.parse(fs.readFileSync(filePath, 'utf8')) as T;
}

async function formatWithPrettier(content: string, filepath: string): Promise<string> {
  const config = (await prettier.resolveConfig(filepath)) ?? {};
  return prettier.format(content, { ...config, filepath });
}

function buildGeneratedCostDataTs(
  skuMap: PriceSkuMapFile,
  regionMap: unknown,
  instanceSpecs: unknown,
): string {
  return `// AUTO-GENERATED by scripts/check-price-coverage.ts from packages/cost-engine/data/*.json. Do not edit by hand.

export interface RegionEquivalenceEntry {
  key: string;
  label: string;
  aws: string;
  gcp: string;
  azure: string;
  oci: string;
  note?: string;
}

export interface InstanceSpecEntry {
  provider: 'aws' | 'gcp' | 'azure' | 'oci';
  instanceType: string;
  family: string;
  vcpu: number;
  memoryGb: number;
  arch: 'x86_64' | 'arm64';
  category: 'compute' | 'database';
  sourceUrl: string;
  verifiedAt: string;
}

export interface KnownUnavailablePriceEntry {
  serviceId: string;
  provider: 'aws' | 'gcp' | 'azure' | 'oci';
  reason: string;
}

export interface PriceSkuMappingEntry {
  serviceId: string;
  provider: 'aws' | 'gcp' | 'azure' | 'oci';
  unitRole: string;
  unit: string;
  filter: Record<string, unknown>;
}

export const CURATED_REGION_MAP: readonly RegionEquivalenceEntry[] = ${JSON.stringify(
    (regionMap as { regions: unknown[] }).regions,
    null,
    2,
  )};

export const CURATED_INSTANCE_SPECS: readonly InstanceSpecEntry[] = ${JSON.stringify(
    (instanceSpecs as { specs: unknown[] }).specs,
    null,
    2,
  )};

export const KNOWN_UNAVAILABLE_SERVICES: readonly KnownUnavailablePriceEntry[] = ${JSON.stringify(
    skuMap.knownUnavailable ?? [],
    null,
    2,
  )};

export const PRICE_SKU_MAPPINGS: readonly PriceSkuMappingEntry[] = ${JSON.stringify(
    skuMap.mappings,
    null,
    2,
  )};
`;
}

export interface CoverageSummaryRow {
  provider: 'aws' | 'gcp' | 'azure' | 'oci';
  totalServices: number;
  freeServices: number;
  nonFreeServices: number;
  mappedServices: number;
  knownUnavailableServices: number;
  missingServiceIds: string[];
  unknownServiceIds: string[];
  transferMappingsCount: number;
}

export function evaluateCoverage(): {
  summaries: CoverageSummaryRow[];
  markdownReport: string;
  generatedTs: string;
  errors: string[];
} {
  const skuMap = readJson<PriceSkuMapFile>(path.join(COST_DATA_DIR, 'price_sku_map.json'));
  const regionMap = readJson<Record<string, unknown>>(path.join(COST_DATA_DIR, 'region_map.json'));
  const instanceSpecs = readJson<Record<string, unknown>>(
    path.join(COST_DATA_DIR, 'instance_specs.json'),
  );

  const errors: string[] = [];
  const summaries: CoverageSummaryRow[] = [];
  const unavailableByProvider = new Map<string, UnavailableEntry[]>();

  for (const entry of skuMap.knownUnavailable ?? []) {
    if (!entry.reason || entry.reason.trim().length < 5) {
      errors.push(`knownUnavailable entry '${entry.serviceId}' is missing an explanation reason.`);
    }
    const list = unavailableByProvider.get(entry.provider) ?? [];
    list.push(entry);
    unavailableByProvider.set(entry.provider, list);
  }

  const perProviderDetails: string[] = [];

  for (const provider of PROVIDERS) {
    const catalog = readJson<CatalogServiceRow[]>(path.join(CATALOG_DIR, `${provider}.json`));
    const catalogIds = new Set(catalog.map((s) => s.id));

    const mappingsForProv = skuMap.mappings.filter((m) => m.provider === provider);
    const serviceMappings = new Map<string, SkuMappingEntry[]>();
    const transferMappings = new Set<string>();

    for (const mapping of mappingsForProv) {
      if (mapping.serviceId.startsWith('transfer.')) {
        transferMappings.add(mapping.serviceId);
        continue;
      }
      const arr = serviceMappings.get(mapping.serviceId) ?? [];
      arr.push(mapping);
      serviceMappings.set(mapping.serviceId, arr);
    }

    const unavailEntries = unavailableByProvider.get(provider) ?? [];
    const unavailById = new Map(unavailEntries.map((u) => [u.serviceId, u.reason]));

    const freeServices = catalog.filter((s) => s.pricing?.model === 'free');
    const nonFreeServices = catalog.filter((s) => s.pricing?.model !== 'free');

    const missingServiceIds: string[] = [];
    for (const svc of nonFreeServices) {
      if (!serviceMappings.has(svc.id) && !unavailById.has(svc.id)) {
        missingServiceIds.push(svc.id);
      }
    }

    const unknownServiceIds: string[] = [];
    for (const id of serviceMappings.keys()) {
      if (!catalogIds.has(id)) {
        unknownServiceIds.push(id);
      }
    }
    for (const id of unavailById.keys()) {
      if (!catalogIds.has(id)) {
        unknownServiceIds.push(id);
      }
    }

    if (missingServiceIds.length > 0) {
      errors.push(
        `[${provider}] Uncovered non-free catalog services (neither mapped nor knownUnavailable with reason): ${missingServiceIds.join(', ')}`,
      );
    }
    if (unknownServiceIds.length > 0) {
      errors.push(
        `[${provider}] Mapping references unknown service IDs: ${unknownServiceIds.join(', ')}`,
      );
    }

    summaries.push({
      provider,
      totalServices: catalog.length,
      freeServices: freeServices.length,
      nonFreeServices: nonFreeServices.length,
      mappedServices: serviceMappings.size,
      knownUnavailableServices: unavailById.size,
      missingServiceIds,
      unknownServiceIds,
      transferMappingsCount: transferMappings.size,
    });

    const lines: string[] = [
      `## ${provider.toUpperCase()} (${catalog.length} services — ${serviceMappings.size} mapped, ${unavailById.size} known-unavailable, ${freeServices.length} free)`,
      '',
      '| Service ID | Price Code | Status | Unit Role(s) / Reason |',
      '|---|---|---|---|',
    ];

    for (const svc of catalog) {
      const code = svc.pricing?.model ?? 'unknown';
      if (code === 'free') {
        lines.push(`| \`${svc.id}\` | \`free\` | free | No provider charge |`);
      } else if (serviceMappings.has(svc.id)) {
        const roles = (serviceMappings.get(svc.id) ?? [])
          .map((m) => `\`${m.unitRole}\``)
          .join(', ');
        lines.push(`| \`${svc.id}\` | \`${code}\` | mapped | ${roles} |`);
      } else if (unavailById.has(svc.id)) {
        lines.push(
          `| \`${svc.id}\` | \`${code}\` | known-unavailable | ${unavailById.get(svc.id)} |`,
        );
      } else {
        lines.push(`| \`${svc.id}\` | \`${code}\` | **MISSING** | Needs mapping or reason |`);
      }
    }

    lines.push('');
    perProviderDetails.push(lines.join('\n'));
  }

  const summaryTable = [
    '# Price Coverage Report',
    '',
    `Generated from \`packages/catalog/data/*.json\` and \`packages/cost-engine/data/price_sku_map.json\` (updated \`${skuMap.updatedAt}\`).`,
    '',
    'CI fails if any non-`free` catalog service is missing from both `mappings` and `knownUnavailable` (with a reason).',
    '',
    '## Summary',
    '',
    '| Provider | Total | Free | Non-Free | Mapped | Known Unavailable | Missing | Transfer SKUs |',
    '|---|---:|---:|---:|---:|---:|---:|---:|',
    ...summaries.map(
      (s) =>
        `| ${s.provider.toUpperCase()} | ${s.totalServices} | ${s.freeServices} | ${s.nonFreeServices} | ${s.mappedServices} | ${s.knownUnavailableServices} | ${s.missingServiceIds.length} | ${s.transferMappingsCount} |`,
    ),
    '',
    ...perProviderDetails,
  ].join('\n');

  const generatedTs = buildGeneratedCostDataTs(skuMap, regionMap, instanceSpecs);

  return { summaries, markdownReport: summaryTable, generatedTs, errors };
}

async function main(): Promise<void> {
  const mode = process.argv.includes('--write') ? 'write' : 'check';
  const result = evaluateCoverage();

  if (result.errors.length > 0) {
    console.error('Price coverage validation failed:');
    for (const err of result.errors) {
      console.error(`  - ${err}`);
    }
    process.exit(1);
  }

  const formattedMd = await formatWithPrettier(result.markdownReport, REPORT_PATH);
  const formattedTs = await formatWithPrettier(result.generatedTs, GENERATED_TS_PATH);

  if (mode === 'write') {
    fs.mkdirSync(path.dirname(REPORT_PATH), { recursive: true });
    fs.mkdirSync(path.dirname(GENERATED_TS_PATH), { recursive: true });
    fs.writeFileSync(REPORT_PATH, formattedMd, 'utf8');
    fs.writeFileSync(GENERATED_TS_PATH, formattedTs, 'utf8');
    console.log(
      'Generated docs/price-coverage.md and packages/cost-engine/src/generated/costData.ts.',
    );
    return;
  }

  const currentMd = fs.existsSync(REPORT_PATH) ? fs.readFileSync(REPORT_PATH, 'utf8') : '';
  const currentTs = fs.existsSync(GENERATED_TS_PATH)
    ? fs.readFileSync(GENERATED_TS_PATH, 'utf8')
    : '';

  if (currentMd !== formattedMd || currentTs !== formattedTs) {
    console.error(
      'Price coverage report or generated costData.ts is out of date. Run: pnpm cost:coverage:write',
    );
    process.exit(1);
  }

  console.log('Price coverage check passed (all 243 cloud services accounted for).');
}

const isEntrypoint =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isEntrypoint) {
  main().catch((err: unknown) => {
    console.error(err);
    process.exit(1);
  });
}
